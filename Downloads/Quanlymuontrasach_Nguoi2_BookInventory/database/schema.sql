CREATE DATABASE IF NOT EXISTS QuanLyNhaSach_Nguoi2 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE QuanLyNhaSach_Nguoi2;

CREATE TABLE IF NOT EXISTS SACH (
    MaSach VARCHAR(50) PRIMARY KEY,
    TenSach VARCHAR(255) NOT NULL,
    TheLoai VARCHAR(150) NOT NULL DEFAULT '',
    TacGia VARCHAR(255) NOT NULL DEFAULT '',
    SoLuongTon INT UNSIGNED NOT NULL DEFAULT 0,
    DonGia DECIMAL(15,2) UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS THAMSO (
    MaThamSo TINYINT UNSIGNED PRIMARY KEY DEFAULT 1,
    SoLuongNhapItNhat INT UNSIGNED NOT NULL DEFAULT 10,
    SoLuongTonToiDaTruocNhap INT UNSIGNED NOT NULL DEFAULT 100
) ENGINE=InnoDB;

INSERT INTO THAMSO (MaThamSo, SoLuongNhapItNhat, SoLuongTonToiDaTruocNhap)
VALUES (1, 10, 100)
ON DUPLICATE KEY UPDATE MaThamSo = VALUES(MaThamSo);

CREATE TABLE IF NOT EXISTS PHIEUNHAP (
    MaPhieuNhap INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    NgayNhap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CHITIETPHIEUNHAP (
    MaPhieuNhap INT UNSIGNED NOT NULL,
    MaSach VARCHAR(50) NOT NULL,
    SoLuongNhap INT UNSIGNED NOT NULL,
    DonGiaNhap DECIMAL(15,2) UNSIGNED NOT NULL,
    PRIMARY KEY (MaPhieuNhap, MaSach),
    CONSTRAINT fk_ctphieunhap_phieunhap FOREIGN KEY (MaPhieuNhap)
        REFERENCES PHIEUNHAP (MaPhieuNhap),
    CONSTRAINT fk_ctphieunhap_sach FOREIGN KEY (MaSach)
        REFERENCES SACH (MaSach)
) ENGINE=InnoDB;

